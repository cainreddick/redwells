#!/usr/bin/env python3
"""Concatenate the source files into single-file NX journals in dist/.

NX plays a journal from one .cs file, so the sources (kept separate for
testing) are merged. Each source file keeps its `using` directives inside its
own namespace block, so the merged file needs no hoisting and the pure-logic
code never sees the NXOpen namespace.

Usage: python3 tools/build_journal.py          (builds every journal)
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
DIST = ROOT / "dist"

# journal file name -> entry file
JOURNALS = {
    "LaserDxf.cs": "entry/LaserDxf.cs",
    "LaserDxfProbe.cs": "entry/LaserDxfProbe.cs",
}
CONFIG = ROOT / "config" / "LaserDxf.config.json"


def build(name, entry):
    parts = [SRC / entry]
    parts += sorted((SRC / "nx").glob("*.cs"))
    parts += sorted((SRC / "core").glob("*.cs"))
    out = [
        "// ============================================================================",
        f"// {name} - generated by tools/build_journal.py from nx-laser-dxf/src.",
        "// Do not edit this file; edit the sources and rebuild.",
        "// Play in NX: Tools > Journal > Play (Alt+F8), browse to this file, Run.",
        "// ============================================================================",
        "",
    ]
    for p in parts:
        out.append(f"// ----- {p.relative_to(SRC).as_posix()} -----")
        out.append(p.read_text(encoding="utf-8").rstrip() + "\n")
    DIST.mkdir(exist_ok=True)
    # CRLF: friendlier for Notepad on Windows; the C# compiler doesn't care.
    text = "\n".join(out).replace("\r\n", "\n").replace("\n", "\r\n")
    (DIST / name).write_bytes(text.encode("utf-8"))
    print(f"built dist/{name} ({len(parts)} files)")


if __name__ == "__main__":
    for n, e in JOURNALS.items():
        build(n, e)
    DIST.mkdir(exist_ok=True)
    (DIST / CONFIG.name).write_bytes(CONFIG.read_text(encoding="utf-8").replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8"))
    print(f"copied dist/{CONFIG.name}")
